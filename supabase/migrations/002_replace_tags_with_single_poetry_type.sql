-- -----------------------------------------------------------------------------
-- 3) Add poetry_type_id to poems (nullable first for safe backfill)
-- -----------------------------------------------------------------------------

alter table public.poems
  add column poetry_type_id bigint references public.poetry_types (id);

comment on column public.poems.poetry_type_id is
  'Exactly one poetry type per poem. Immutable after submission for normal clients.';

-- Development-safe backfill: if poems already exist without a type, assign
-- Verso libre (free-verse) temporarily so NOT NULL can be applied.
do $$
declare
  existing_poems integer;
  free_verse_id bigint;
begin
  select count(*)::integer into existing_poems from public.poems;

  select pt.id
  into strict free_verse_id
  from public.poetry_types pt
  where pt.slug = 'free-verse';

  if existing_poems > 0 then
    update public.poems
    set poetry_type_id = free_verse_id
    where poetry_type_id is null;
  end if;
end;
$$;

alter table public.poems
  alter column poetry_type_id set not null;

-- Ensure no lingering default: new poems must supply poetry_type_id explicitly.
alter table public.poems
  alter column poetry_type_id drop default;

create index poems_poetry_type_id_idx on public.poems (poetry_type_id);

comment on table public.poems is
  'Poems start as pending and require exactly one poetry_type_id. Moderation status is separate from author hide/soft-delete. Clients cannot change poetry type after submission.';


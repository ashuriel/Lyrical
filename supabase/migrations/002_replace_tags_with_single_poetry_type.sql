-- -----------------------------------------------------------------------------
-- 1) poetry_types catalog
-- Controlled catalog data: clients may read only; privileged roles maintain it.
-- -----------------------------------------------------------------------------

create table public.poetry_types (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null,
  created_at timestamptz not null default now(),
  constraint poetry_types_name_unique unique (name),
  constraint poetry_types_slug_unique unique (slug),
  constraint poetry_types_name_length check (char_length(name) between 1 and 60),
  constraint poetry_types_slug_length check (char_length(slug) between 1 and 60)
);

comment on table public.poetry_types is
  'Controlled poetry-form catalog. Spanish name is the display value; English slug is the stable programmatic id. Normal clients cannot write this table.';

comment on column public.poetry_types.name is
  'Spanish display name for the poetry type.';

comment on column public.poetry_types.slug is
  'Stable English identifier used by application code.';


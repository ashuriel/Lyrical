-- -----------------------------------------------------------------------------
-- 7) Poem security updates (preserve existing rules + immutable poetry type)
-- -----------------------------------------------------------------------------

-- Tighten INSERT RLS: poetry_type_id required; still own author + pending only.
drop policy if exists "poems_insert_own_pending" on public.poems;

create policy "poems_insert_own_pending"
  on public.poems
  for insert
  to authenticated
  with check (
    author_id = auth.uid()
    and status = 'pending'
    and poetry_type_id is not null
  );

-- Column privileges: clients insert only author/title/content/type.
-- Clients update only hide / soft-delete fields.
revoke insert on table public.poems from authenticated;
grant insert (author_id, title, content, poetry_type_id)
  on table public.poems to authenticated;

revoke update on table public.poems from authenticated;
grant update (is_hidden, deleted_at)
  on table public.poems to authenticated;

-- Replace insert guard: require poetry_type_id; do not invent a default type.
create or replace function public.enforce_poem_insert_guards()
returns trigger
language plpgsql
as $$
begin
  -- Privileged backends may insert freely; clients are constrained below.
  if coalesce(auth.role(), '') = 'service_role'
     or current_user in ('postgres', 'supabase_admin') then
    return new;
  end if;

  if auth.uid() is null then
    raise exception 'authentication required to create poems';
  end if;

  if new.author_id is distinct from auth.uid() then
    raise exception 'author_id must equal auth.uid()';
  end if;

  if new.poetry_type_id is null then
    raise exception 'poetry_type_id is required';
  end if;

  new.status := 'pending';
  new.is_hidden := coalesce(new.is_hidden, false);
  new.published_at := null;
  new.deleted_at := null;

  return new;
end;
$$;

comment on function public.enforce_poem_insert_guards() is
  'Forces pending client inserts with auth.uid() as author and a required poetry_type_id. Does not default the poetry type.';

-- Replace update guard: clients cannot change poetry_type_id after submission.
-- Privileged moderation path unchanged (published_at on first approval).
create or replace function public.enforce_poem_update_guards()
returns trigger
language plpgsql
as $$
declare
  is_privileged boolean;
begin
  -- Single BEFORE UPDATE trigger keeps poem update order deterministic.
  new.updated_at := now();

  is_privileged :=
    coalesce(auth.role(), '') = 'service_role'
    or current_user in ('postgres', 'supabase_admin');

  -- Privileged moderation path.
  -- When status becomes approved for the first time, stamp published_at.
  -- Do not overwrite an existing published_at on later privileged updates.
  if is_privileged then
    if new.status = 'approved'
       and old.status is distinct from 'approved'::public.poem_status
       and new.published_at is null then
      new.published_at := now();
    end if;
    return new;
  end if;

  -- Authenticated client path: protected columns stay immutable.
  if new.id is distinct from old.id then
    raise exception 'poems.id is immutable';
  end if;

  if new.author_id is distinct from old.author_id then
    raise exception 'poems.author_id is immutable';
  end if;

  if new.title is distinct from old.title
     or new.content is distinct from old.content then
    raise exception 'poem title and content cannot be edited after submission';
  end if;

  if new.status is distinct from old.status then
    raise exception 'poem moderation status cannot be changed by this role';
  end if;

  if new.published_at is distinct from old.published_at then
    raise exception 'published_at cannot be changed by clients';
  end if;

  -- Product rule: poetry type is chosen at submission and cannot change later.
  if new.poetry_type_id is distinct from old.poetry_type_id then
    raise exception 'poetry_type_id cannot be changed after submission';
  end if;

  if new.created_at is distinct from old.created_at then
    raise exception 'poems.created_at is immutable';
  end if;

  -- Soft-delete is one-way for clients: clearing deleted_at is not allowed.
  if old.deleted_at is not null
     and new.deleted_at is distinct from old.deleted_at then
    raise exception 'soft-deleted poems cannot be restored by clients';
  end if;

  return new;
end;
$$;

comment on function public.enforce_poem_update_guards() is
  'Client guard for protected poem columns including immutable poetry_type_id; privileged path sets published_at on first approval.';
